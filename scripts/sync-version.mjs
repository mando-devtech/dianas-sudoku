// Copies the version from package.json into the files the browser actually loads:
//   - public/version.js  → shown in the UI
//   - public/sw.js       → cache name, so every release invalidates the old offline cache
// Runs automatically on `npm version <patch|minor|major>` (see "version" script).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const { version } = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const today = new Date().toLocaleDateString('en-CA'); // YYYY-MM-DD, local time

writeFileSync(
  new URL('public/version.js', root),
  `/* Generated by scripts/sync-version.mjs — do not edit by hand.
   Source of truth: package.json "version". */
self.APP_VERSION = '${version}';
self.APP_BUILD_DATE = '${today}';
`
);

const swUrl = new URL('public/sw.js', root);
const sw = readFileSync(swUrl, 'utf8');
const updated = sw.replace(/const APP_VERSION = '[^']*';/, `const APP_VERSION = '${version}';`);
if (updated === sw && !sw.includes(`const APP_VERSION = '${version}';`)) {
  console.error('sync-version: no encontré "const APP_VERSION = ..." en public/sw.js');
  process.exit(1);
}
writeFileSync(swUrl, updated);

console.log(`✔ Versión sincronizada: v${version} (${today})`);

